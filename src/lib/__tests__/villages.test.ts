import { readFileSync, readdirSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { PREFIX_DISTRICT } from '../../features/game/districts'
import { countLitByVillage, villageOf, type DistrictVillages, type Village } from '../villages'

const square = (x0: number, y0: number, x1: number, y1: number): [number, number][] => [
  [x0, y0],
  [x1, y0],
  [x1, y1],
  [x0, y1],
  [x0, y0],
]

const village = (id: string, geometry: Village['geometry'], bbox: Village['bbox']): Village => ({
  id,
  name: id,
  total: 0,
  bbox,
  geometry,
})

// A: 0..10 square with a hole 4..6.  B: MultiPolygon of two squares at 20..30 and 40..50.
const A = village('A', { type: 'Polygon', coordinates: [square(0, 0, 10, 10), square(4, 4, 6, 6)] }, [0, 0, 10, 10])
const B = village(
  'B',
  { type: 'MultiPolygon', coordinates: [[square(20, 0, 30, 10)], [square(40, 0, 50, 10)]] },
  [20, 0, 50, 10],
)
const vs = [A, B]

describe('villageOf', () => {
  it('finds the polygon containing the point', () => {
    expect(villageOf([1, 1], vs)?.id).toBe('A')
    expect(villageOf([9, 9], vs)?.id).toBe('A')
  })
  it('treats holes as outside', () => {
    expect(villageOf([5, 5], vs)).toBeNull()
  })
  it('handles every part of a MultiPolygon, and the gap between parts', () => {
    expect(villageOf([25, 5], vs)?.id).toBe('B')
    expect(villageOf([45, 5], vs)?.id).toBe('B')
    expect(villageOf([35, 5], vs)).toBeNull() // inside B's bbox, outside both parts
  })
  it('returns null outside every village', () => {
    expect(villageOf([-1, 5], vs)).toBeNull()
    expect(villageOf([15, 5], vs)).toBeNull()
    expect(villageOf([1, 1], [])).toBeNull()
  })
})

describe('countLitByVillage', () => {
  it('counts distinct trees per village and skips trees outside', () => {
    const m = countLitByVillage(
      [
        { id: 't1', lngLat: [1, 1] },
        { id: 't2', lngLat: [2, 2] },
        { id: 't1', lngLat: [1, 1] }, // same tree twice
        { id: 't3', lngLat: [25, 5] },
        { id: 't4', lngLat: [5, 5] }, // in the hole
        { id: 't5', lngLat: [100, 100] },
      ],
      vs,
    )
    expect(m.get('A')).toBe(2)
    expect(m.get('B')).toBe(1)
    expect(m.size).toBe(2)
  })
  it('is empty with no trees', () => {
    expect(countLitByVillage([], vs).size).toBe(0)
  })
})

describe('public/data/villages (generated by scripts/build_villages.py)', () => {
  const dir = 'public/data/villages'
  const read = (prefix: string) => JSON.parse(readFileSync(`${dir}/${prefix}.json`, 'utf8')) as DistrictVillages

  it('has one file per district prefix', () => {
    expect(readdirSync(dir).map((f) => f.replace('.json', '')).sort()).toEqual(Object.keys(PREFIX_DISTRICT).sort())
  })
  it('DA: shape, totals, and its own tree location lands in the right village', () => {
    const d = read('DA')
    expect(d.district).toBe(PREFIX_DISTRICT.DA)
    expect(d.attribution).toContain('國土測繪中心')
    expect(d.villages.length).toBeGreaterThan(0)
    expect(d.villages.reduce((s, v) => s + v.total, 0)).toBeGreaterThan(0)
    for (const v of d.villages) {
      expect(v.id).toMatch(/^\d+$/)
      expect(v.bbox).toHaveLength(4)
      expect(['Polygon', 'MultiPolygon']).toContain(v.geometry.type)
    }
  })
  it('DA: real trees land in DA villages (loader and build agree on coordinates)', () => {
    const d = read('DA')
    const trees = JSON.parse(readFileSync('public/data/trees/DA.json', 'utf8')).trees as Record<string, [number, number]>
    const sample = Object.values(trees).slice(0, 300)
    const hit = sample.filter(([lon, lat]) => villageOf([lon, lat], d.villages)).length
    expect(hit / sample.length).toBeGreaterThan(0.95)
  })
  it('456 villages across the 12 files', () => {
    const n = Object.keys(PREFIX_DISTRICT).reduce((s, p) => s + read(p).villages.length, 0)
    expect(n).toBe(456)
  })
})
